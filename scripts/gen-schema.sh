#!/bin/sh
# Regenerates packages/schema/generated/index.ts from the Rust model (ts-rs).
# Usage: scripts/gen-schema.sh
# Output is deterministic: files are concatenated in sorted order.
set -eu

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT_DIR="$ROOT/packages/schema/generated"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

# shellcheck source=/dev/null
[ -f "$HOME/.cargo/env" ] && . "$HOME/.cargo/env"

cd "$ROOT"
TS_RS_EXPORT_DIR="$TMP" cargo test -p dormbit-core --locked export_bindings >/dev/null

mkdir -p "$OUT_DIR"
{
  echo "// Generated by scripts/gen-schema.sh from dormbit-core. Do not edit."
  for f in $(find "$TMP" -maxdepth 1 -type f -exec basename {} \; | LC_ALL=C sort); do
    echo ""
    # Drop ts-rs headers and cross-file imports; everything lives in one module.
    grep -v -e '^// This file was generated' -e '^import type' "$TMP/$f" | sed '/^$/N;/^\n$/D'
  done
} > "$OUT_DIR/index.ts"

echo "wrote $OUT_DIR/index.ts"
